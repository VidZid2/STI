/**
 * Quick export - fetches data and exports in one call
 */
export const quickExportClassGrades = async (
    _courseCode: string,
    _section: string,
    format: 'pdf' | 'excel',
    fetchGradesFunction: () => Promise<ClassGradesSummary>
): Promise<void> => {
    try {
        const data = await fetchGradesFunction();
        
        if (format === 'pdf') {
            exportGradesToPDF(data);
        } else {
            exportGradesToExcel(data);
        }
    } catch (error) {
        console.error('Export failed:', error);
        throw error;
    }
};

