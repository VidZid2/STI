/**
 * Export Utilities
 * Provides PDF and Excel export functionality for grades and reports
 */

import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import * as XLSX from 'xlsx';

// ============================================
// TYPES
// ============================================
export interface GradeExportData {
    studentName: string;
    studentId: string;
    section: string;
    course: string;
    assignments: {
        title: string;
        score: number;
        maxScore: number;
        percentage: number;
        status: string;
        submittedAt: string;
    }[];
    averageGrade: number;
    totalPoints: number;
    maxPoints: number;
}

export interface ClassGradesSummary {
    courseName: string;
    courseCode: string;
    section: string;
    semester: string;
    teacherName: string;
    exportDate: string;
    students: {
        rank: number;
        name: string;
        studentId: string;
        assignments: number[];
        average: number;
        grade: string;
        remarks: string;
    }[];
    assignmentTitles: string[];
}

// ============================================
// HELPER FUNCTIONS
// ============================================
const getLetterGrade = (percentage: number): string => {
    if (percentage >= 97) return 'A+';
    if (percentage >= 93) return 'A';
    if (percentage >= 90) return 'A-';
    if (percentage >= 87) return 'B+';
    if (percentage >= 83) return 'B';
    if (percentage >= 80) return 'B-';
    if (percentage >= 77) return 'C+';
    if (percentage >= 73) return 'C';
    if (percentage >= 70) return 'C-';
    if (percentage >= 67) return 'D+';
    if (percentage >= 63) return 'D';
    if (percentage >= 60) return 'D-';
    return 'F';
};

const getRemarks = (percentage: number): string => {
    if (percentage >= 75) return 'PASSED';
    return 'FAILED';
};

