/**
 * Export class grades to Excel
 */
export const exportGradesToExcel = (data: ClassGradesSummary): void => {
    // Create workbook
    const wb = XLSX.utils.book_new();
    
    // Header info
    const headerData = [
        ['GRADE REPORT'],
        [`${data.courseName} (${data.courseCode})`],
        [],
        ['Section:', data.section],
        ['Semester:', data.semester],
        ['Instructor:', data.teacherName],
        ['Date Generated:', data.exportDate],
        [],
    ];
    
    // Table headers
    const tableHeaders = ['Rank', 'Student Name', 'Student ID', ...data.assignmentTitles, 'Average', 'Grade', 'Remarks'];
    
    // Table data
    const tableData = data.students.map(student => [
        student.rank,
        student.name,
        student.studentId,
        ...student.assignments,
        student.average,
        student.grade,
        student.remarks,
    ]);
    
    // Combine all data
    const wsData = [...headerData, tableHeaders, ...tableData];
    
    // Create worksheet
    const ws = XLSX.utils.aoa_to_sheet(wsData);
    
    // Set column widths
    ws['!cols'] = [
        { wch: 6 },  // Rank
        { wch: 25 }, // Name
        { wch: 15 }, // ID
        ...data.assignmentTitles.map(() => ({ wch: 10 })),
        { wch: 10 }, // Average
        { wch: 8 },  // Grade
        { wch: 10 }, // Remarks
    ];
    
    // Add worksheet to workbook
    XLSX.utils.book_append_sheet(wb, ws, 'Grades');
    
    // Save
    XLSX.writeFile(wb, `Grade_Report_${data.courseCode}_${data.section}_${new Date().toISOString().split('T')[0]}.xlsx`);
};

/**
 * Export attendance to Excel
 */
export const exportAttendanceToExcel = (data: {
    courseName: string;
    section: string;
    dates: string[];
    students: {
        name: string;
        studentId: string;
        attendance: ('P' | 'A' | 'L' | 'E')[]; // Present, Absent, Late, Excused
        totalPresent: number;
        totalAbsent: number;
        attendanceRate: number;
    }[];
}): void => {
    const wb = XLSX.utils.book_new();
    
    const headerData = [
        ['ATTENDANCE REPORT'],
        [`${data.courseName} - ${data.section}`],
        [],
        ['Legend: P = Present, A = Absent, L = Late, E = Excused'],
        [],
    ];
    
    const tableHeaders = ['Student Name', 'Student ID', ...data.dates, 'Present', 'Absent', 'Rate'];
    
    const tableData = data.students.map(student => [
        student.name,
        student.studentId,
        ...student.attendance,
        student.totalPresent,
        student.totalAbsent,
        `${student.attendanceRate.toFixed(1)}%`,
    ]);
    
    const wsData = [...headerData, tableHeaders, ...tableData];
    const ws = XLSX.utils.aoa_to_sheet(wsData);
    
    XLSX.utils.book_append_sheet(wb, ws, 'Attendance');
    XLSX.writeFile(wb, `Attendance_${data.section}_${new Date().toISOString().split('T')[0]}.xlsx`);
};

