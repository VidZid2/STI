/**
 * Export class grades to PDF
 */
export const exportGradesToPDF = (data: ClassGradesSummary): void => {
    const doc = new jsPDF('landscape', 'mm', 'a4');
    const pageWidth = doc.internal.pageSize.getWidth();
    
    // Header
    doc.setFontSize(18);
    doc.setFont('helvetica', 'bold');
    doc.text('GRADE REPORT', pageWidth / 2, 15, { align: 'center' });
    
    doc.setFontSize(14);
    doc.text(`${data.courseName} (${data.courseCode})`, pageWidth / 2, 23, { align: 'center' });
    
    doc.setFontSize(10);
    doc.setFont('helvetica', 'normal');
    doc.text(`Section: ${data.section}`, 14, 33);
    doc.text(`Semester: ${data.semester}`, 14, 38);
    doc.text(`Instructor: ${data.teacherName}`, 14, 43);
    doc.text(`Date Generated: ${data.exportDate}`, pageWidth - 14, 33, { align: 'right' });
    
    // Build table headers
    const headers = ['Rank', 'Student Name', 'Student ID', ...data.assignmentTitles, 'Average', 'Grade', 'Remarks'];
    
    // Build table body
    const body = data.students.map(student => [
        student.rank.toString(),
        student.name,
        student.studentId,
        ...student.assignments.map(score => score.toFixed(1)),
        student.average.toFixed(2),
        student.grade,
        student.remarks,
    ]);
    
    // Generate table
    autoTable(doc, {
        head: [headers],
        body: body,
        startY: 50,
        theme: 'grid',
        styles: {
            fontSize: 8,
            cellPadding: 2,
        },
        headStyles: {
            fillColor: [59, 130, 246], // Blue
            textColor: 255,
            fontStyle: 'bold',
        },
        alternateRowStyles: {
            fillColor: [248, 250, 252],
        },
        columnStyles: {
            0: { halign: 'center', cellWidth: 12 }, // Rank
            1: { cellWidth: 40 }, // Name
            2: { cellWidth: 25 }, // ID
        },
    });
    
    // Footer
    const finalY = (doc as jsPDF & { lastAutoTable: { finalY: number } }).lastAutoTable.finalY || 200;
    doc.setFontSize(8);
    doc.setTextColor(100);
    doc.text('This is a computer-generated document. No signature required.', pageWidth / 2, finalY + 10, { align: 'center' });
    doc.text(`Generated by eLMS Teacher Portal - ${new Date().toLocaleString()}`, pageWidth / 2, finalY + 15, { align: 'center' });
    
    // Save
    doc.save(`Grade_Report_${data.courseCode}_${data.section}_${new Date().toISOString().split('T')[0]}.pdf`);
};

/**
 * Export individual student report to PDF
 */
export const exportStudentReportPDF = (data: GradeExportData): void => {
    const doc = new jsPDF('portrait', 'mm', 'a4');
    const pageWidth = doc.internal.pageSize.getWidth();
    
    // Header
    doc.setFontSize(18);
    doc.setFont('helvetica', 'bold');
    doc.text('STUDENT GRADE REPORT', pageWidth / 2, 20, { align: 'center' });
    
    // Student Info
    doc.setFontSize(12);
    doc.setFont('helvetica', 'normal');
    doc.text(`Student: ${data.studentName}`, 14, 35);
    doc.text(`Student ID: ${data.studentId}`, 14, 42);
    doc.text(`Section: ${data.section}`, 14, 49);
    doc.text(`Course: ${data.course}`, 14, 56);
    
    // Summary Box
    doc.setFillColor(248, 250, 252);
    doc.roundedRect(pageWidth - 80, 30, 66, 30, 3, 3, 'F');
    doc.setFontSize(10);
    doc.text('Overall Grade', pageWidth - 47, 38, { align: 'center' });
    doc.setFontSize(24);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(59, 130, 246);
    doc.text(`${data.averageGrade.toFixed(1)}%`, pageWidth - 47, 52, { align: 'center' });
    doc.setTextColor(0);
    
    // Assignments Table
    const headers = ['Assignment', 'Score', 'Max', '%', 'Status', 'Submitted'];
    const body = data.assignments.map(a => [
        a.title,
        a.score.toString(),
        a.maxScore.toString(),
        `${a.percentage.toFixed(1)}%`,
        a.status,
        a.submittedAt,
    ]);
    
    autoTable(doc, {
        head: [headers],
        body: body,
        startY: 70,
        theme: 'striped',
        styles: { fontSize: 9 },
        headStyles: {
            fillColor: [59, 130, 246],
            textColor: 255,
        },
    });
    
    // Save
    doc.save(`Student_Report_${data.studentName.replace(/\s+/g, '_')}_${new Date().toISOString().split('T')[0]}.pdf`);
};

